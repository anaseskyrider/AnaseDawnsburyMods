    public static class CommonRequirements
    {
        public static Func<Creature, string?> StanceRestriction(QEffectId stanceId)
        {
            return self =>
            {
                if (self.HasEffect(stanceId))
                    return "You're already in this stance.";
                return null;
            };
        }
    }
    
