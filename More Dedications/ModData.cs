            #region Local Functions

            // I removed ID_PREPEND from all FeatNames and Traits.
            // As a result, I need to replace:
            
            // - Modded dedications to modded
            // ("MoreDedications.MaulerDedication" -> "MaulerDedication")
            void ReplaceModDedWithModDed(Trait archetype, FeatName newDedication)
            {
                string oldTechnical = ID_PREPEND + archetype.ToStringOrTechnical() + "Dedication";
                ModManager.RegisterFeatNameReplacement(oldTechnical, newDedication);
            }

            // - Modded dedications to base
            // ("MoreDedications.MartialArtist" -> "MartialArtistDedication")
            void ReplaceModDedWithBaseDed(Trait archetype)
            {
                string traitTech = archetype.ToStringOrTechnical();
                string oldTechnical = ID_PREPEND + traitTech + "Dedication";
                if (AllFeats.GetFeatByFeatNameOrStringOptional(null, traitTech + "Dedication") is { } newDed)
                    ModManager.RegisterFeatNameReplacement(oldTechnical, newDed.FeatName);
            }

            // - Modded feats to modded feats
            // ("MoreDedications.Archetype.Mauler.ClearTheWay" -> "ClearTheWay")
            void ReplaceModWithMod(string oldMod, FeatName newMod)
            {
                ModManager.RegisterFeatNameReplacement(oldMod, newMod);
            }
            
            // - Modded class feats
            // ("MoreDedications.Class.Fighter.ShieldedStride" -> "ShieldedStride")
            void ReplaceModClassWithModClass(string oldClass, FeatName newClass)
            {
                ModManager.RegisterFeatNameReplacement(oldClass, newClass);
            }
            
            // - Modded feats for modded archetypes
            // ("MoreDedications.Class.Fighter.ShieldedStride" + "ForArchetype" + "MoreDedications.Mauler" -> "ShieldedStrideForArchetypeMauler")
            void ReplaceModClassForWithModClassFor(string oldMod, Trait forArchetype, FeatName newMod)
            {
                ModManager.RegisterFeatNameReplacement(
                    oldMod + "ForArchetype" + ID_PREPEND + forArchetype.ToStringOrTechnical(),
                    newMod);
            }
            
            // - Base feats for modded archetypes
            // (FeatName.Knockdown + "ForArchetype" + "MoreDedications.Mauler" -> "KnockdownForArchetypeMauler")
            void ReplaceBaseForWithModFor(FeatName baseFeat, Trait forArchetype, FeatName newMod)
            {
                ModManager.RegisterFeatNameReplacement(
                    baseFeat.ToStringOrTechnical() + "ForArchetype" + ID_PREPEND + forArchetype.ToStringOrTechnical(),
                    newMod);
            }
            
            // - Base game feats for base game archetypes
            // - Modded feats with base-like names for base game archetypes
            // (FeatName.BrawlingFocus + "ForArchetype" + "MoreDedications.MartialArtist" -> "BrawlingFocusForArchetypeMartialArtist")
            void ReplaceBaseForWithBaseFor(FeatName baseFeat, Trait forArchetype)
            {
                string baseTech = baseFeat.ToStringOrTechnical();
                string traitTech = forArchetype.ToStringOrTechnical();
                string oldTech = baseTech + "ForArchetype" + ID_PREPEND + traitTech;
                string newTech =  baseTech + "ForArchetype" + traitTech;
                if (AllFeats.GetFeatByFeatNameOrStringOptional(null, newTech) is { } newFeat)
                    ModManager.RegisterFeatNameReplacement(
                        oldTech,
                        newFeat.FeatName);
            }

            #endregion
